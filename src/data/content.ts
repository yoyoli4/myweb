// ---------------------------------------------------------------------------
// 类型定义（一般不用改）
// ---------------------------------------------------------------------------

export interface Place {
  id: string            // 唯一英文标识，随便起，不重复即可
  name: string          // 地点名称
  lat: number           // 纬度
  lng: number           // 经度
  date: string          // 到访时间：'2025-03' 或 '2025-03-18'
  text: string          // 卡片里的简短文字，一两句话
  photos: string[]      // 照片链接数组，一张或多张都行，按顺序展示
}

export type ArticleBlock =
  | { type: 'p'; text: string }
  | { type: 'h2'; text: string }
  | { type: 'quote'; text: string }
  | { type: 'image'; src: string; alt?: string }

export interface Article {
  slug: string          // 网址后缀，如 /articles/night-walk
  title: string
  cover: string
  date: string          // 'YYYY-MM-DD'
  excerpt: string       // 列表页的摘要
  blocks: ArticleBlock[]
}

export interface Painting {
  id: string
  title: string         // 画名
  date: string          // 'YYYY-MM' 或 'YYYY-MM-DD'
  medium?: string       // 材质/媒介，如「布面丙烯」
  image: string         // 画作图片链接
  note?: string         // 一句疯话，可以不填
}

